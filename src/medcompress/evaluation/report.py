"""LaTeX tables and number macros for the paper, generated from the results summary.

Every file written here starts with a "generated" header and must never be edited
by hand: numbers reach the paper only through these files
(``docs/FINAL_GOAL.md`` section 4). With no results yet, cells read ``--`` so the
paper still compiles.
"""

from __future__ import annotations

import math
import re
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

import pandas as pd

from medcompress.registry import BUDGET_IDS, PRIMARY_BUDGET, REGISTRY, SAME_AS_E7

GENERATED_HEADER = "% GENERATED by scripts/08_aggregate_results.py from results/. Do not edit.\n"
MISSING = "--"

ACCURACY = "overall_accuracy"
SMALL_RECALL = "small_finding_recall"
MASK_EFFECT = "lesion_mask_effect"
HEADLINE_METRICS: tuple[str, ...] = (ACCURACY, SMALL_RECALL, MASK_EFFECT)
EFFICIENCY_METRICS: tuple[tuple[str, str], ...] = (
    ("num_parameters", "Params"),
    ("file_size_bytes", "File size"),
    ("peak_memory_bytes", "Peak memory"),
    ("cold_latency_s", "Cold latency (s)"),
    ("warm_latency_s", "Warm latency (s)"),
    ("low_precision_kernels_ok", "Kernels OK"),
)
PRIMARY_COMPARISON_NAME = "E7_vs_best"
ABLATION_IDS: tuple[str, ...] = ("A1", "A2", "A3", "A4", "A5", "A6")


def arm_labels(experiment_id: str) -> list[str]:
    """Return ``ID`` or ``ID:variant`` labels for one registry experiment."""
    spec = REGISTRY[experiment_id]
    return [f"{experiment_id}:{v}" for v in spec.variants] if spec.variants else [experiment_id]


def _lookup(summary: pd.DataFrame) -> dict[tuple[str, str, str], Mapping[str, float]]:
    if summary.empty:
        return {}
    return {
        (
            str(r["experiment"]),
            str(r["budget"] if isinstance(r["budget"], str) else ""),
            str(r["metric"]),
        ): r
        for r in summary.to_dict("records")
    }


def _finite(value: object) -> bool:
    return isinstance(value, int | float) and not math.isnan(float(value))


def fmt_value(value: object, digits: int = 3) -> str:
    """Format a number, or ``--`` when missing."""
    return f"{float(value):.{digits}f}" if _finite(value) else MISSING


def fmt_mean_sd(row: Mapping[str, float] | None, digits: int = 3) -> str:
    """Format ``mean $\\pm$ sd`` (sd left out for one seed), or ``--``."""
    if row is None or not _finite(row.get("mean")):
        return MISSING
    text = fmt_value(row["mean"], digits)
    if _finite(row.get("sd")):
        text += f" $\\pm$ {fmt_value(row['sd'], digits)}"
    return text


def fmt_ci(row: Mapping[str, float] | None, digits: int = 3) -> str:
    """Format ``[low, high]``, or ``--``."""
    if row is None or not (_finite(row.get("ci_low")) and _finite(row.get("ci_high"))):
        return MISSING
    return f"[{fmt_value(row['ci_low'], digits)}, {fmt_value(row['ci_high'], digits)}]"


def latex_escape(text: str) -> str:
    """Escape LaTeX special characters in a cell."""
    return re.sub(r"([_%&#$])", r"\\\1", text)


def tabular(columns: Sequence[str], rows: Iterable[Sequence[str]], align: str | None = None) -> str:
    """Return a booktabs tabular with the generated header."""
    spec = align or "l" * len(columns)
    lines = [GENERATED_HEADER, f"\\begin{{tabular}}{{{spec}}}", "\\toprule"]
    lines.append(" & ".join(columns) + " \\\\")
    lines.append("\\midrule")
    for row in rows:
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


def main_table(summary: pd.DataFrame) -> str:
    """T2: accuracy, small-finding recall and lesion-mask effect per arm and budget."""
    look = _lookup(summary)
    rows = []
    for exp in ("E2",):
        for arm in arm_labels(exp):
            rows.append(
                ["ref", latex_escape(arm)]
                + [fmt_mean_sd(look.get((arm, "", m))) for m in HEADLINE_METRICS]
            )
    for arm in arm_labels("E3"):
        rows.append(
            ["meas.", latex_escape(arm)]
            + [fmt_mean_sd(look.get((arm, "", m))) for m in HEADLINE_METRICS]
        )
    for budget in BUDGET_IDS:
        for exp in ("E5", "E6", "E7", "E8"):
            for arm in arm_labels(exp):
                rows.append(
                    [budget, latex_escape(arm)]
                    + [fmt_mean_sd(look.get((arm, budget, m))) for m in HEADLINE_METRICS]
                )
    return tabular(
        ["Budget", "Arm", "Accuracy", "Small-finding recall", "Lesion-mask effect"], rows
    )


def primary_table(summary: pd.DataFrame, name: str = PRIMARY_COMPARISON_NAME) -> str:
    """T3: E7 minus the best of E5/E6 at B2, with CIs and Holm-adjusted p-values."""
    look = _lookup(summary)
    cells = []
    for metric in (SMALL_RECALL, MASK_EFFECT):
        diff = look.get((name, PRIMARY_BUDGET, f"diff:{metric}"))
        holm = look.get((name, PRIMARY_BUDGET, f"p_holm:{metric}"))
        value = fmt_value(diff["mean"]) if diff is not None else MISSING
        cells.append(f"{value} {fmt_ci(diff)}" if diff is not None else MISSING)
        cells.append(fmt_value(holm["mean"]) if holm is not None else MISSING)
    return tabular(
        [
            "Comparison",
            "$\\Delta$ small-finding recall [95\\% CI]",
            "$p_{\\mathrm{Holm}}$",
            "$\\Delta$ lesion-mask effect [95\\% CI]",
            "$p_{\\mathrm{Holm}}$",
        ],
        [["E7 vs best of E5/E6", *cells]],
    )


def ablation_table(summary: pd.DataFrame) -> str:
    """T4: E7 and A1-A6 at B2.

    An arm of ``SAME_AS_E7`` without runs of its own shows E7's numbers, labelled ``(= E7)``.
    """
    look = _lookup(summary)
    metrics = (SMALL_RECALL, MASK_EFFECT)
    rows = []
    for arm in ["E7", *[a for exp in ABLATION_IDS for a in arm_labels(exp)]]:
        source, label = arm, latex_escape(arm)
        own = any((arm, PRIMARY_BUDGET, m) in look for m in metrics)
        if arm in SAME_AS_E7 and not own:
            source, label = "E7", f"{latex_escape(arm)} (= E7)"
        rows.append([label] + [fmt_mean_sd(look.get((source, PRIMARY_BUDGET, m))) for m in metrics])
    return tabular(["Arm", "Small-finding recall", "Lesion-mask effect"], rows)


def efficiency_table(summary: pd.DataFrame) -> str:
    """T5: measured footprint per arm (budget-matched arms at B2)."""
    look = _lookup(summary)
    rows = []
    for exp in ("E0", "E1", "E2", "E3", "E4", "E5", "E6", "E7", "E8", "E9"):
        budget = PRIMARY_BUDGET if REGISTRY[exp].budgets else ""
        for arm in arm_labels(exp):
            rows.append(
                [latex_escape(arm)]
                + [fmt_mean_sd(look.get((arm, budget, m)), digits=3) for m, _ in EFFICIENCY_METRICS]
            )
    return tabular(["Arm", *[label for _, label in EFFICIENCY_METRICS]], rows)


def external_table(summary: pd.DataFrame) -> str:
    """T6: headline metrics on the deduplicated external test set (``external:`` metrics)."""
    look = _lookup(summary)
    rows = []
    for arm, budget in [
        ("E0", ""),
        ("E2", ""),
        *[(a, "") for a in arm_labels("E3")],
        *[(a, PRIMARY_BUDGET) for e in ("E5", "E6", "E7") for a in arm_labels(e)],
    ]:
        rows.append(
            [latex_escape(arm)]
            + [fmt_mean_sd(look.get((arm, budget, f"external:{m}"))) for m in HEADLINE_METRICS]
        )
    return tabular(["Arm", "Accuracy", "Small-finding recall", "Lesion-mask effect"], rows)


def setup_data_table(rows: pd.DataFrame) -> str:
    """T1: aggregate data statistics from ``results/data/summary.csv`` (metric, value)."""
    data = rows[rows["source"].str.contains("/data/")] if not rows.empty else rows
    body = [
        [latex_escape(str(r["metric"])), fmt_value(r["value"], 4)] for r in data.to_dict("records")
    ]
    return tabular(["Quantity", "Value"], body or [[MISSING, MISSING]])


_DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]


def macro_name(*parts: str) -> str:
    """Return a LaTeX-safe macro name (letters only) built from the parts."""
    words: list[str] = []
    for part in parts:
        for token in re.split(r"[^0-9A-Za-z]+", part):
            if not token:
                continue
            token = "".join(_DIGITS[int(c)] if c.isdigit() else c for c in token)
            words.append(token[0].upper() + token[1:])
    return "res" + "".join(words)


def numbers_tex(summary: pd.DataFrame) -> str:
    """Return ``\\newcommand`` macros for every summarised number (value and CI bounds)."""
    lines = [GENERATED_HEADER]
    seen: set[str] = set()
    for row in summary.to_dict("records") if not summary.empty else []:
        budget = row["budget"] if isinstance(row["budget"], str) else ""
        base = macro_name(str(row["experiment"]), budget, str(row["metric"]))
        for suffix, key in (("", "mean"), ("Sd", "sd"), ("Low", "ci_low"), ("High", "ci_high")):
            if _finite(row.get(key)):
                name = base + suffix
                if name in seen:
                    raise ValueError(f"Macro name collision: {name}")
                seen.add(name)
                lines.append(f"\\newcommand{{\\{name}}}{{{fmt_value(row[key])}}}")
    lines.append("")
    return "\n".join(lines)


TABLE_WRITERS = {
    "main.tex": main_table,
    "primary.tex": primary_table,
    "ablations.tex": ablation_table,
    "efficiency.tex": efficiency_table,
    "external.tex": external_table,
}


def write_tables(rows: pd.DataFrame, summary: pd.DataFrame, tables_dir: Path) -> list[Path]:
    """Write every table and ``numbers.tex`` to ``tables_dir``; return the paths."""
    tables_dir = Path(tables_dir)
    tables_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, writer in TABLE_WRITERS.items():
        path = tables_dir / name
        path.write_text(writer(summary), encoding="utf-8")
        written.append(path)
    setup = tables_dir / "setup_data.tex"
    setup.write_text(setup_data_table(rows), encoding="utf-8")
    numbers = tables_dir / "numbers.tex"
    numbers.write_text(numbers_tex(summary), encoding="utf-8")
    return [*written, setup, numbers]
